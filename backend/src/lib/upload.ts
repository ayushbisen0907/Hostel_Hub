import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import type { Response } from 'express'
import multer from 'multer'
import { env } from '../config/env.js'
import { badRequest, notFound } from './errors.js'

export const uploadRoot = path.resolve(env.UPLOAD_DIR)
fs.mkdirSync(uploadRoot, { recursive: true })

const ALLOWED = new Set(['image/jpeg', 'image/png', 'image/webp', 'image/heic', 'application/pdf'])

/**
 * multer instance for document/photo uploads (field name: "file").
 * Files are stored with random names; the original name is kept in the DB.
 */
export const upload = multer({
  storage: multer.diskStorage({
    destination: uploadRoot,
    filename: (_req, file, cb) => {
      const ext = path.extname(file.originalname).toLowerCase().replace(/[^.a-z0-9]/g, '').slice(0, 6)
      cb(null, `${Date.now()}-${crypto.randomBytes(8).toString('hex')}${ext}`)
    },
  }),
  limits: { fileSize: env.MAX_UPLOAD_MB * 1024 * 1024, files: 1 },
  fileFilter: (_req, file, cb) => {
    if (ALLOWED.has(file.mimetype)) cb(null, true)
    else cb(badRequest('Only JPG, PNG, WEBP, HEIC images or PDF files are allowed'))
  },
})

/** Stream a stored file to the client. `download` forces a save dialog. */
export function sendStoredFile(res: Response, storageKey: string, fileName: string, mimeType: string, download = false) {
  // storageKey is generated by us, but guard against path traversal anyway
  const full = path.join(uploadRoot, path.basename(storageKey))
  if (!fs.existsSync(full)) throw notFound('File')
  res.setHeader('Content-Type', mimeType)
  res.setHeader('X-Content-Type-Options', 'nosniff')
  res.setHeader(
    'Content-Disposition',
    `${download ? 'attachment' : 'inline'}; filename="${encodeURIComponent(fileName)}"`,
  )
  fs.createReadStream(full).pipe(res)
}

export function removeStoredFile(storageKey: string) {
  const full = path.join(uploadRoot, path.basename(storageKey))
  fs.promises.unlink(full).catch(() => {})
}
