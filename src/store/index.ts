export type HostelerInput = Omit<
  Hosteler,
  | 'id'
  | 'createdAt'
  | 'roomId'
  | 'bedId'
  | 'status'
  | 'checkOutDate'
  | 'depositRefunded'
  // credentials are generated by the store at admission
  | 'loginId'
  | 'passwordHash'
  | 'tempPassword'
  | 'mustChangePassword'
  | 'passwordChangedAt'
  | 'lastLoginAt'
>

export type HostelerLoginResult =
  | { ok: true; mustChangePassword: boolean }
  | { ok: false; error: string }

export type HostelInput = Omit<Hostel, 'id' | 'createdAt' | 'code' | 'hostelerSeq'> & { code?: string }

export interface AdmitInput {
  hosteler: HostelerInput
  bedId: ID | null
  reserveOnly: boolean // true = hold bed, check in later
  depositPayment: { amount: number; mode: Payment['mode']; reference: string } | null
  generateFirstInvoice: boolean
}

export interface CheckOutInput {
  date: string
  depositRefund: number
  deductionNote: string
}

export type RoomInput = Omit<Room, 'id'>

